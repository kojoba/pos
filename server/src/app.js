import express from 'express';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import helmet from 'helmet';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import authRoutes from './routes/auth.routes.js';
import productRoutes from './routes/products.routes.js';
import orderRoutes from './routes/orders.routes.js';
import stockRoutes from './routes/stock.routes.js';
import warehouseRoutes from './routes/warehouse.routes.js';
import userRoutes from './routes/users.routes.js';
import deliveryRoutes from './routes/deliveries.routes.js';
import dashboardRoutes from './routes/dashboard.routes.js';
import customerRoutes from './routes/customers.routes.js';
import feedbackRoutes from './routes/feedback.routes.js';
import branchRoutes from './routes/branches.routes.js';
import paymentRoutes from './routes/payments.routes.js';
const app=express();
app.use(helmet({contentSecurityPolicy:false}));
app.use(cors({origin:process.env.CLIENT_ORIGIN||'http://localhost:5173',credentials:true}));
app.use(express.urlencoded({extended:false,limit:'10kb'}));
app.use(express.json({limit:'100kb',verify:(req,_res,buffer)=>{req.rawBody=Buffer.from(buffer)}}));app.use(cookieParser());
app.get('/api/health',(_req,res)=>res.json({ok:true}));
app.use('/api/auth',authRoutes);
app.use('/api/products',productRoutes);
app.use('/api/orders',orderRoutes);
app.use('/api/payments',paymentRoutes);
app.use('/api/stock',stockRoutes);
app.use('/api/warehouse',warehouseRoutes);
app.use('/api/users',userRoutes);
app.use('/api/deliveries',deliveryRoutes);
app.use('/api/dashboard',dashboardRoutes);
app.use('/api/customers',customerRoutes);
app.use('/api/feedback',feedbackRoutes);
app.use('/api/branches',branchRoutes);
app.use((err,_req,res,_next)=>{console.error(err);res.status(500).json({error:'Something went wrong. Please try again.'});});
const here=path.dirname(fileURLToPath(import.meta.url));
const clientDist=path.resolve(here,'../../client/dist');
app.use(express.static(clientDist));
app.get(/.*/,(req,res,next)=>req.path.startsWith('/api/')?next():res.sendFile(path.join(clientDist,'index.html'),err=>err&&next(err)));
export default app;
